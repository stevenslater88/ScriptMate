def test_frontend_title_NBSP_between_tokens_not_a_character() -> None:
    raw = _mk_script("SUBTITLE LINE ONE").replace(
        "THE GREAT SNACK HEIST", "THE\u00A0GREAT SNACK HEIST"
    )
    parsed = _run_frontend_parser(raw)
    _skip_if_no_ts_loader(parsed)
    chars = {str(c).upper().strip() for c in parsed["characters"]}
    assert "THE GREAT SNACK HEIST" not in chars
    assert "THE\u00A0GREAT SNACK HEIST" not in chars
    assert {"JACK", "EMILY", "BELLA", "LILY"}.issubset(chars)


@pytest.mark.parametrize("label,ch", _INVISIBLE_CHARS)
def test_frontend_backend_sets_agree_with_invisible_injection(label: str, ch: str) -> None:
    """The TWO parsers MUST produce the same character identity set
    when PyPDF2 injects an invisible intra-token char into the
    subtitle. Otherwise the review screen and the saved script
    disagree about the cast."""
    subtitle = f"SCRIPT{ch}M8 STRESS-TEST SCRIPT"
    raw = _mk_script(subtitle)
    frontend = _run_frontend_parser(raw)
    _skip_if_no_ts_loader(frontend)
    backend = fallback_parse_script(raw)
    fe_chars = {str(c).upper().strip() for c in frontend["characters"]}
    be_chars = {str(c).upper().strip() for c in backend.get("characters", [])}
    assert fe_chars == be_chars, (
        f"[{label}] FE/BE drift.\nfe={sorted(fe_chars)}\nbe={sorted(be_chars)}"
    )
    assert fe_chars == {"JACK", "EMILY", "BELLA", "LILY"}


